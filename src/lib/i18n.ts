export const t = (lang: Lang) => dicts[lang];

/** Перевод кода ошибки из БД (raise exception 'CODE') */
export function errorText(lang: Lang, message: string | undefined) {
  const d = dicts[lang] as Record<string, string>;
  const code = (message || "").trim();
  // Обрыв связи: запрос не дошёл, ничего не оформлено, форма и корзина на месте
  if (/failed to fetch|networkerror|load failed|network request failed/i.test(code)) return d.err_network;
  return d[`err_${code}`] ?? d.err_generic;
}
