"use client";

import { Fragment, type ReactNode } from "react";

/**
 * Переводы панели сотрудников. Ключ — русский текст (он же показывается, если перевода нет),
 * значение — [узбекский, английский]. Подстановки: {0}, {1}…
 * Язык хранится в localStorage и выставляется в StaffApp перед отрисовкой вкладок.
 */
export type StaffLang = "uz" | "ru" | "en";
export const STAFF_LANGS: StaffLang[] = ["uz", "ru", "en"];
export const STAFF_LANG_KEY = "bolakay-staff-lang";

let current: StaffLang = "ru";
export const setStaffLang = (l: StaffLang) => {
  current = l;
};
export const staffLang = () => current;

export function s(ru: string, ...args: (string | number)[]): string {
  const tr = current === "ru" ? ru : DICT[ru]?.[current === "uz" ? 0 : 1] ?? ru;
  return args.length ? tr.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? "")) : tr;
}

/** Мини-разметка в переводах: **жирный** и `код` */
export function rich(text: string): ReactNode {
  return text.split(/(\*\*[^*]+\*\*|`[^`]+`)/g).map((part, i) =>
    part.startsWith("**") ? <b key={i}>{part.slice(2, -2)}</b> : part.startsWith("`") ? <code key={i}>{part.slice(1, -1)}</code> : <Fragment key={i}>{part}</Fragment>,
  );
}

